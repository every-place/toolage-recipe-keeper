// Keeps the app itself loadable with a weak kitchen Wi-Fi signal.
// Recipes and photos always come fresh from the server (never cached here).
const CACHE = "rk-shell-v1";

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(["/", "/manifest.webmanifest"])));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== "GET" || url.origin !== location.origin || url.pathname.startsWith("/api/")) return;
  // Network first, falling back to the cached copy when offline.
  event.respondWith(
    fetch(event.request)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(event.request.mode === "navigate" ? "/" : event.request, copy));
        }
        return res;
      })
      .catch(() => caches.match(event.request.mode === "navigate" ? "/" : event.request))
  );
});
